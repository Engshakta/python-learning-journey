# Replaces entire domain name
print("www.netcad.com".replace("netcad.com", "pythoninstitute.org"))

# Replaces all occurrences of "is"
print("This is it!".replace("is", "are"))

# Replaces the first occurrences of "is"
print("This is it!".replace("is", "are", 1))

# Removing substrings using an empty string
print("Apple juice".replace("juice", " " ))